def show_tutorial_menu():
    """Display an interactive tutorial menu."""
    while True:
        print("\n" + "═" * 50)
        print("  📚 德州扑克学习中心")
        print("═" * 50)
        for i, (title, _) in enumerate(CHAPTERS, 1):
            print(f"  [{i}] {title}")
        print("  [0] 返回主菜单")
        print("═" * 50)

        choice = input("  请选择要学习的内容（输入数字）: ").strip()
        if choice == "0":
            break
        if choice.isdigit():
            idx = int(choice) - 1
            if 0 <= idx < len(CHAPTERS):
                title, content = CHAPTERS[idx]
                print(content)
                input("  按回车键继续...")
            else:
                print("  ❌ 无效选项")
        else:
            print("  ❌ 请输入数字")


